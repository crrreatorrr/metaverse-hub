import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { loadModule } from '../unit/harness';
const m=loadModule();
const api=m.global.ShooterVerificationCleanup as {operate(ctx:object,nk:unknown,payload:string,operation:string):string};
const request={operatorId:'restore-operator',keyId:'one',token:'a'.repeat(43),requestId:'one',body:{runId:'run-id'}};
m.nk.sqlCalls.length=0;
assert.equal(JSON.parse(api.operate({},m.nk,JSON.stringify(request),'inspect')).state,'authorization_denied');
assert.equal(m.nk.sqlCalls.length,0);
const actor={userId:'a0570000-0000-4000-8000-000000000001'};
const calls:unknown[][]=[];
m.nk.onSql('SELECT game.shooter_verification_maintain',(args)=>{calls.push(args);return[{result:'{"state":"inspected"}'}];});
assert.equal(JSON.parse(api.operate(actor,m.nk,JSON.stringify(request),'inspect')).state,'inspected');
assert.equal(calls[0]![0],actor.userId);
assert.equal(calls[0]![3],createHash('sha256').update('shooter-operator-v1\n'+request.token).digest('hex'));
assert.ok(!JSON.stringify(calls).includes(request.token),'operator bearer never passed to SQL');
assert.equal(JSON.parse(api.operate(actor,m.nk,JSON.stringify({...request,payAmount:20}),'inspect')).reason,'malformed');
assert.equal(JSON.parse(api.operate(actor,m.nk,JSON.stringify(request),'arbitrary_sql')).reason,'malformed');
assert.equal(calls.length,1);
console.log('unused scoped retention helper binds actor and bounded exact envelope without raw credentials');
