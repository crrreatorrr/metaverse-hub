import assert from 'node:assert/strict';
import { FixedSlotParticipants, CreateRateBudget, allowOrdinaryCreateRetry, assertOriginalCredential,
  PVP_REPLACEMENT_LIMIT, PVP_INITIAL_LIMIT, ROOM_OPERATION_LIMIT } from './background-policy.ts';
assert.equal(PVP_REPLACEMENT_LIMIT, 100); assert.equal(PVP_INITIAL_LIMIT + PVP_REPLACEMENT_LIMIT, 110);
assert.equal(ROOM_OPERATION_LIMIT, 440);
let created = 0;
const pool = new FixedSlotParticipants<{ accountId: string; sessionId: string }>(value => value);
const make = async () => { const n = String(++created).padStart(12, '0'); return { accountId: `00000000-0000-4000-8000-${n}`, sessionId: `00000000-0000-4000-9000-${n}` }; };
for (let slot = 0; slot < 10; slot++) await pool.get(slot, make);
for (let round = 0; round < 10; round++) for (let slot = 0; slot < 10; slot++) await pool.get(slot, make);
assert.equal(created, 20, 'rematch policy reuses its20 original bindings without invoking the auth factory again');
const evidence = pool.evidence(); assert.equal(evidence.length, 10);
assert.equal(new Set(evidence.flatMap(row => row.accountBindingHashes)).size, 20);
assert.equal(new Set(evidence.flatMap(row => row.sessionBindingHashes)).size, 20);
assert.ok(!JSON.stringify(evidence).includes('00000000-0000-4000'));
const pair = await pool.get(0, make); const original = pair[0].sessionId;
pair[0].sessionId = '00000000-0000-4000-9000-999999999999';
await assert.rejects(pool.get(0, make), /original_participant_changed/); pair[0].sessionId = original;
assert.equal(allowOrdinaryCreateRetry('already_in_match', 1, 1), true);
assert.equal(allowOrdinaryCreateRetry('already_in_match', 3, 1), false);
assert.equal(allowOrdinaryCreateRetry('already_in_match', 1, 9900), false);
for (const reason of ['rate_limited', 'wrong_scope', 'session_expired', 'unknown']) assert.equal(allowOrdinaryCreateRetry(reason, 1, 1), false);
const rate = new CreateRateBudget(), account = evidence[0].accountBindingHashes[0];
for (let i = 0; i < 5; i++) rate.note(account, i);
assert.throws(() => rate.note(account, 100), /rate_budget_exhausted/); rate.note(account, 60005);
const identity = pair[0], claims = { uid: identity.accountId, exp: 100, vrs: { scope: 'game', game: 'sproto-shooter', sid: identity.sessionId } };
const token = 'header.' + Buffer.from(JSON.stringify(claims)).toString('base64url') + '.signature';
assertOriginalCredential(token, identity, 99000);
assert.throws(() => assertOriginalCredential(token, identity, 100000), /expired_or_changed/);
assert.throws(() => assertOriginalCredential(token, { ...identity, sessionId: pair[1].sessionId }, 99000), /expired_or_changed/);
console.log('Fixed original participants, finite replacement work and ordinary-create retry/rate policy canaries passed');
