import assert from 'node:assert/strict';
import { FinishBarrier } from './finish-barrier.ts';
const signal = new AbortController();
const staggered = new FinishBarrier(20);
let released = false;
const early = Array.from({ length: 19 }, (_, actor) => staggered.arrive(0, String(actor), signal.signal));
Promise.all(early).then(() => { released = true; });
await new Promise(resolve => setTimeout(resolve, 10100));
assert.equal(released, false, 'valid staggered upload is not failed by the former10s first-arrival timer');
const last = staggered.arrive(0, '19', signal.signal);
assert.ok((await Promise.all([...early, last])).every(value => value.synchronized));
const failed = new FinishBarrier(20);
const peers = Array.from({ length: 19 }, (_, actor) => failed.arrive(1, String(actor), signal.signal));
failed.fail(1, 'failed-uploader');
assert.ok((await Promise.all(peers)).every(value => !value.synchronized), 'one failed uploader releases accepted peers without waiting900s');
assert.equal(failed.failures()[0].acknowledgedActors, 19);
assert.equal(failed.failures()[0].failedActorBindingHashes.length, 1);
const cancelled = new FinishBarrier(20), abort = new AbortController();
const pending = cancelled.arrive(0, '0', abort.signal); abort.abort();
await assert.rejects(pending, /aborted/);
console.log('full-wave staggered upload, failed-uploader release and run-deadline synchronization canaries passed');
