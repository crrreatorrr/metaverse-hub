import assert from 'node:assert/strict';
import { beginClientMeasurement, type ClientProbe } from './client-gate.ts';
const signal = new AbortController();
let callback!: Parameters<ClientProbe['start']>[1];
let done!: (value: Record<string, unknown>) => void;
let starts = 0;
const probe: ClientProbe = { async start(_signal, ready) { starts++; callback = ready; return new Promise(resolve => { done = resolve; }); }, async close() { return { state: 'closed' }; } };
const gate = beginClientMeasurement(probe, signal.signal);
await Promise.resolve();
callback!({ observedMonoMs: performance.now(), recordedFrames: 0, runBindingHash: 'a'.repeat(64) });
assert.equal(gate.evidence().reason, null, 'zero input cannot release native-recording gate');
callback!({ observedMonoMs: performance.now(), recordedFrames: 1, runBindingHash: 'a'.repeat(64) });
await gate.ready; assert.equal(starts, 1); assert.equal(gate.evidence().reason, 'observed_positive_native_recording');
const frozen = gate.evidence(); done({ actors: [] }); await gate.result;
assert.deepEqual(gate.evidence(), frozen, 'settlement cannot rewrite gate observation');
const rejected = beginClientMeasurement({ ...probe, async start() { throw new Error('private exception must never be serialized'); } }, new AbortController().signal);
await rejected.ready; assert.equal(rejected.evidence().reason, 'client_failed_before_ready'); assert.equal((await rejected.result).state, 'failed');
const abort = new AbortController();
const pending = beginClientMeasurement({ ...probe, async start() { return new Promise(() => undefined); } }, abort.signal);
abort.abort(); await pending.ready; assert.equal(pending.evidence().reason, 'global_measurement_abort');
console.log('readonly native recording gate releases full protocol workload on success, failure or global stop');
