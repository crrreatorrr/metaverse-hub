// Fail when the vendored Sproto Fighter simulation drifts from the pinned
// Fighter commit, from the fingerprint its own bundle body hashes to, or from
// the fingerprint the duel server expects on HELLO. Then compare that pin to
// Sproto-Fighter main (public; no custom secret).
//
//   node scripts/check-sproto-sim-version.mjs
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const bundlePath = join(root, 'server/modules/vendor/sproto-sim.js');
const pinPath = join(root, 'server/modules/vendor/sproto-sim.pin.json');
const duelPath = join(root, 'server/modules/src/sproto_duel.ts');
const serverSrc = join(root, 'server/modules/src');
const FIGHTER_REPO = 'crrreatorrr/Sproto-Fighter';

const HEADER = /^\/\/ Sproto Fighter simulation ([0-9a-f]{16}), generated by scripts\/build-sim-bundle\.mjs\. Do not edit\.\nvar SPROTO_SIM_VERSION = '([0-9a-f]{16})';\n/;

function serverFiles(dir = serverSrc, out = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) serverFiles(path, out);
    else if (name.endsWith('.ts')) out.push(path);
  }
  return out;
}

function assignedFingerprint(name) {
  const pattern = new RegExp(`(?:export\\s+)?(?:var|let|const)\\s+${name}\\s*=\\s*['"]([0-9a-f]{16})['"]`);
  for (const file of serverFiles()) {
    const found = pattern.exec(readFileSync(file, 'utf8'));
    if (found) return found[1];
  }
  return null;
}

function checkLocal() {
  const errors = [];
  const bundle = readFileSync(bundlePath, 'utf8');
  const header = HEADER.exec(bundle);
  if (!header) {
    errors.push('vendor/sproto-sim.js is missing the generated SPROTO_SIM_VERSION header');
  } else if (header[1] !== header[2]) {
    errors.push(`bundle comment ${header[1]} != SPROTO_SIM_VERSION ${header[2]}`);
  }
  const headerVersion = header ? header[2] : '';
  if (header) {
    const computed = createHash('sha256').update(bundle.slice(header[0].length)).digest('hex').slice(0, 16);
    if (computed !== headerVersion) {
      errors.push(`bundled code fingerprint ${computed} != SPROTO_SIM_VERSION ${headerVersion}`);
    }
    for (const match of bundle.slice(header[0].length).matchAll(/(?:exports\.SIM_VERSION\s*=\s*|SIM_VERSION\s*=\s*)['"]([0-9a-f]{16})['"]/g)) {
      if (match[1] !== headerVersion) errors.push(`bundle exports SIM_VERSION ${match[1]} != header ${headerVersion}`);
    }
  }

  let pin = null;
  try {
    pin = JSON.parse(readFileSync(pinPath, 'utf8'));
  } catch (error) {
    errors.push(`could not read ${pinPath}: ${error instanceof Error ? error.message : String(error)}`);
  }
  if (pin) {
    if (!/^[0-9a-f]{40}$/.test(String(pin.fighterCommit || ''))) errors.push('pin fighterCommit must be a full 40-character sha');
    if (!/^[0-9a-f]{16}$/.test(String(pin.simVersion || ''))) errors.push('pin simVersion must be a 16-character hex fingerprint');
    if (headerVersion && pin.simVersion && headerVersion !== pin.simVersion) {
      errors.push(`bundle SPROTO_SIM_VERSION ${headerVersion} != pin ${pin.simVersion}`);
    }
  }

  const duel = readFileSync(duelPath, 'utf8');
  const comparisons = [];
  const comparison = /body\[(["'])sim\1\]\s*!==\s*([A-Za-z0-9_]+|'(?:[0-9a-f]{16})'|"(?:[0-9a-f]{16})")/g;
  for (const match of duel.matchAll(comparison)) {
    const rhs = match[2];
    const around = duel.slice(match.index, match.index + 400);
    if (!around.includes('sim_mismatch')) {
      errors.push('HELLO sim comparison does not cancel with sim_mismatch');
      continue;
    }
    comparisons.push(rhs);
    const quoted = rhs.match(/^['"]([0-9a-f]{16})['"]$/);
    const value = quoted ? quoted[1] : (assignedFingerprint(rhs) ?? (rhs === 'SPROTO_SIM_VERSION' ? headerVersion : null));
    if (!value) errors.push(`HELLO sim is compared to ${rhs}, which does not resolve to a fingerprint`);
    else if (pin?.simVersion && value !== pin.simVersion) errors.push(`server expected fingerprint ${value} (${rhs}) != pin ${pin.simVersion}`);
  }
  if (comparisons.length === 0) errors.push('sproto_duel.ts does not compare HELLO sim to an expected fingerprint');
  return { errors, pin, headerVersion };
}

function versionFromBody(text) {
  const direct = text.match(/export const SIM_VERSION = '([0-9a-f]{16})'/);
  if (direct) return direct[1];
  try {
    const parsed = JSON.parse(text);
    if (typeof parsed.content === 'string') {
      const decoded = Buffer.from(parsed.content, 'base64').toString('utf8');
      const again = decoded.match(/export const SIM_VERSION = '([0-9a-f]{16})'/);
      if (again) return again[1];
    }
  } catch {
    // Not a GitHub contents JSON body.
  }
  return '';
}

async function fetchText(url, token) {
  const headers = {
    Accept: 'application/vnd.github.raw',
    'User-Agent': 'metaverse-hub-sproto-sim-check',
    'X-GitHub-Api-Version': '2022-11-28',
  };
  if (token) headers.Authorization = `Bearer ${token}`;
  const response = await fetch(url, { headers, signal: AbortSignal.timeout(20000) });
  return { status: response.status, text: await response.text() };
}

async function readRemoteSimVersion(ref) {
  const api = `https://api.github.com/repos/${FIGHTER_REPO}/contents/src/net/simVersion.ts?ref=${encodeURIComponent(ref)}`;
  const raw = `https://raw.githubusercontent.com/${FIGHTER_REPO}/${encodeURIComponent(ref)}/src/net/simVersion.ts`;
  const token = process.env.GITHUB_TOKEN || '';
  const auths = token ? [token, ''] : [''];
  let last = 'no response';
  for (const auth of auths) {
    for (let attempt = 1; attempt <= 3; attempt++) {
      try {
        const result = await fetchText(api, auth);
        const version = versionFromBody(result.text);
        if (result.status === 200 && version) return version;
        last = `GitHub API HTTP ${result.status}`;
        if (result.status === 429 || result.status >= 500) {
          await new Promise((resolve) => setTimeout(resolve, 1000 * attempt));
          continue;
        }
        break;
      } catch (error) {
        last = error instanceof Error ? error.message : String(error);
        await new Promise((resolve) => setTimeout(resolve, 1000 * attempt));
      }
    }
    try {
      const result = await fetchText(raw, '');
      const version = versionFromBody(result.text);
      if (result.status === 200 && version) return version;
      last = `raw GitHub HTTP ${result.status}`;
    } catch (error) {
      last = error instanceof Error ? error.message : String(error);
    }
  }
  throw new Error(`could not read Fighter src/net/simVersion.ts at ${ref} (${last})`);
}

async function checkUpstream(pin) {
  const pinned = await readRemoteSimVersion(pin.fighterCommit);
  if (pinned !== pin.simVersion) {
    throw new Error(`Fighter ${pin.fighterCommit} SIM_VERSION ${pinned} != pin ${pin.simVersion}`);
  }
  const mainVersion = await readRemoteSimVersion('main');
  if (mainVersion !== pin.simVersion) {
    throw new Error(`Fighter main SIM_VERSION ${mainVersion} != pinned ${pin.simVersion} (${pin.fighterCommit}). Refresh the hub bundle before online matches drift.`);
  }
  console.log(`Fighter main SIM_VERSION ${mainVersion} matches pin ${pin.fighterCommit}`);
}

const local = checkLocal();
if (local.errors.length) {
  for (const error of local.errors) console.error(`FAIL: ${error}`);
  process.exit(1);
}
try {
  await checkUpstream(local.pin);
} catch (error) {
  console.error(`FAIL: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}
console.log(`PASS: SPROTO_SIM_VERSION ${local.headerVersion} matches the pin and the server HELLO check`);
